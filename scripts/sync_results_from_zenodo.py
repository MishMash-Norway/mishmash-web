#!/usr/bin/env python3
"""Sync datasets, software and other deposits from Zenodo (issue #48).

Two ways a deposit belongs to MishMash: it is in the Zenodo community
"mishmash", or it names the Research Council grant of the centre. Both are
queried through Zenodo's public REST API and written, deduplicated by DOI, to
site/_data/zenodo_records.yml, which the results page and the open data use.
Records that already appear in the NVA results (same DOI) are kept but marked,
so a deposit is never listed twice.

Usage:
  python3 scripts/sync_results_from_zenodo.py            # write the data file
  python3 scripts/sync_results_from_zenodo.py --dry-run  # print what would be written
"""
from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from pathlib import Path

import requests
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from repo_paths import SITE_ROOT

API = "https://zenodo.org/api/records"
COMMUNITY = "mishmash"
GRANT = "357438"
UA = {"User-Agent": "MishMash-web-sync/1.0 (https://mishmash.no; contact@mishmash.no)"}
OUT = SITE_ROOT / "_data" / "zenodo_records.yml"
NVA = SITE_ROOT / "_data" / "mishmash_results.yml"
DOI_RE = re.compile(r"\b(10\.\d{4,9}/[^\s\"'<>?#]+?)(?=[.,;)\]]*(?:[\s?#]|$))", re.I)


def fetch(params: dict) -> list[dict]:
    hits, page = [], 1
    while True:
        r = requests.get(API, params={**params, "size": 25, "page": page, "sort": "mostrecent"}, headers=UA, timeout=60)
        r.raise_for_status()
        data = r.json()
        hits += data["hits"]["hits"]
        if len(hits) >= data["hits"]["total"] or not data["hits"]["hits"]:
            return hits
        page += 1


def simplify(hit: dict, membership: str) -> dict:
    m = hit.get("metadata", {})
    files = hit.get("files") or []
    creators = [{"name": c.get("name"), "orcid": c.get("orcid")} for c in m.get("creators", [])]
    return {
        "id": hit.get("id"),
        "doi": (hit.get("doi") or m.get("doi") or "").lower() or None,
        "concept_doi": (hit.get("conceptdoi") or m.get("conceptdoi") or None),
        "title": m.get("title"),
        "type": (m.get("resource_type") or {}).get("type"),
        "subtype": (m.get("resource_type") or {}).get("subtype"),
        "date": m.get("publication_date"),
        "creators": [c for c in creators if c["name"]],
        "licence": (m.get("license") or {}).get("id"),
        "keywords": m.get("keywords") or [],
        "url": (hit.get("links") or {}).get("self_html") or f"https://zenodo.org/records/{hit.get('id')}",
        "files": len(files),
        "size_bytes": sum(int(f.get("size") or 0) for f in files),
        "membership": membership,
    }


def nva_dois(path: Path = NVA) -> set[str]:
    if not path.exists():
        return set()
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    out = set()
    for r in data.get("results") or []:
        text = " ".join([r.get("url") or "", (r.get("citation") or {}).get("details") or ""])
        for mm in DOI_RE.finditer(text):
            out.add(mm.group(1).rstrip(".").lower())
    return out


def merge(community_hits: list[dict], grant_hits: list[dict], in_nva: set[str]) -> list[dict]:
    by_doi: dict[str, dict] = {}
    for membership, hits in (("community", community_hits), ("grant", grant_hits)):
        for h in hits:
            rec = simplify(h, membership)
            key = rec["doi"] or str(rec["id"])
            if key in by_doi:
                if by_doi[key]["membership"] != membership:
                    by_doi[key]["membership"] = "community and grant"
                continue
            by_doi[key] = rec
    records = sorted(by_doi.values(), key=lambda r: (r["date"] or "", r["title"] or ""), reverse=True)
    for r in records:
        r["in_nva"] = bool(r["doi"] and r["doi"] in in_nva)
    return records


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    community = fetch({"communities": COMMUNITY})
    grant = fetch({"q": f"grants.code:{GRANT}"})
    records = merge(community, grant, nva_dois())
    payload = {
        "synced_at": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "community": f"https://zenodo.org/communities/{COMMUNITY}/",
        "grant": GRANT,
        "records": records,
    }
    text = "# Generated by scripts/sync_results_from_zenodo.py. Do not edit.\n" + yaml.safe_dump(payload, allow_unicode=True, sort_keys=False)
    if args.dry_run:
        print(text)
    else:
        OUT.write_text(text, encoding="utf-8")
    print(f"zenodo: {len(records)} records ({len(community)} in the community, {len(grant)} with the grant)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
