#!/usr/bin/env python3
"""Fetch what the Research Council of Norway has granted MishMash.

Reads the centre's project page in Prosjektbanken (the Research Council's
public project database), whose page data carries the amount, the programme
and the years, and writes them to site/_data/centre_funding.yml. The facts
page and the structured data read the amount from there, so it is never typed.

    python3 scripts/fetch_centre_funding.py            # write the file
    python3 scripts/fetch_centre_funding.py --dry-run  # print what would be written
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from pathlib import Path

import requests
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from repo_paths import SITE_ROOT

CENTRE = SITE_ROOT / "_data" / "centre.yml"
OUT = SITE_ROOT / "_data" / "centre_funding.yml"
NEXT_DATA = re.compile(r'<script id="__NEXT_DATA__"[^>]*>(.*?)</script>', re.S)


def funding_from_page(html: str) -> dict:
    """The amount, programme and years from a Prosjektbanken project page."""
    match = NEXT_DATA.search(html)
    if not match:
        raise ValueError("no page data in the Prosjektbanken page")
    project = json.loads(match.group(1))["props"]["pageProps"]["initialState"]["PROJECT"]["project"]
    activity = project.get("currentActivity") or {}
    amount = activity.get("totalFunding") or project.get("totalFunding")
    if not amount:
        raise ValueError("the project page gives no amount")
    duration = project.get("duration") or {}
    return {
        "amount_nok": round(float(amount)),
        "amount_million_nok": round(float(amount) / 1e6, 1),   # for display; Liquid cannot format numbers
        "programme": (activity.get("activity") or "").split("-")[0],
        "start_year": duration.get("startYear"),
        "end_year": duration.get("endYear"),
        "funding_bodies": project.get("fundingBodies") or [],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    url = yaml.safe_load(CENTRE.read_text(encoding="utf-8"))["funder"]["url"]
    response = requests.get(url, headers={"User-Agent": "mishmash.no"}, timeout=60)
    response.raise_for_status()
    record = {"source": url, "fetched": dt.date.today().isoformat(), **funding_from_page(response.text)}
    text = ("# Generated by scripts/fetch_centre_funding.py from the Research Council's\n"
            "# project database. Do not edit by hand.\n" + yaml.safe_dump(record, allow_unicode=True, sort_keys=False))
    if args.dry_run:
        print(text)
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"centre funding: NOK {record['amount_nok']:,} from {record['programme']}, "
              f"{record['start_year']}-{record['end_year']} -> {OUT.relative_to(SITE_ROOT.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
